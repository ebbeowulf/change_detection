#!/usr/bin/env python3
"""Zero-shot recall from a fixed basket of reference categories and the target's estimated size.

The COCO categories are split at random into a basket (--basket_size, e.g. 40) and targets (the rest).
For each target query (its category name), using the open-vocabulary score f(img, Q):
  1. Threshold: the score that a given share (the specificity level, e.g. 0.9) of the training-pool
     images WITHOUT the target fall below.
  2. Query vector: for every basket category k, always in the same order,
       acc   share of k's images scoring above the threshold ("acceptance rate")
       auc   how well the query's scores separate k's images from the rest (same at every level)
       rel   mean score of k's images minus the threshold
     measured on the training pool (--features chooses which are used).
  3. Target size: the target's typical size from a lookup table (--sizes_file, e.g. generated by a
     VLM), used on a log scale. No labels of the target are used.
  4. True recall: share of test-set images WITH the target that score above the threshold.

For each specificity level separately, these predict true recall:
  mean          P(Q|spec):            average true recall of the other 79 categories
  size_*        P(Q|spec, size):      target size only, trained on the other 79 categories
  acc_*         P(Q|spec, acc):       basket query vector, trained on the other basket targets
  acc+size_*    P(Q|spec, acc, size): basket query vector + target size, trained on the other targets
where * is ridge (weighted sum, large weights penalized) or forest (random forest). All are evaluated
by leaving one target out at a time and scored on the same targets for each basket. The experiment
repeats for each seed in --basket_seeds, each with a different random basket.

Reports, in recall units, per basket and averaged over baskets, at each specificity level: the typical
|predicted - true recall| and the error that 90% of held-out predictions stay within.
Writes results_dir/<model>/basket_recall[_tag].csv and, with --plot 1, plots/basket_recall[_tag].png.
"""
import argparse
import csv
import json
import os

import matplotlib
matplotlib.use("Agg")  # write files only; no display needed
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestRegressor
from sklearn.linear_model import Ridge
from sklearn.metrics import roc_auc_score
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

import models


def label_matrix(results_dir, categories, n_images):
    """(images x categories) table: 1 = image contains the category, 0 = it does not (exhaustive labels)."""
    col = {c: j for j, c in enumerate(categories)}
    Y = np.zeros((n_images, len(categories)), dtype=np.int8)
    with open(results_dir + "/labels.csv") as f:
        for r in csv.DictReader(f):
            Y[int(r["row"]), col[r["category"]]] = 1
    return Y


def make_test_mask(index, test_split, extra_test, seed):
    """Test = all of test_split + whole groups from other splits until extra_test images are added."""
    split = np.array([r["split"] for r in index])
    group = np.array([r["group"] for r in index])
    test = split == test_split
    if extra_test <= 0:
        return test
    groups, counts = np.unique(group[~test], return_counts=True)
    order = np.random.default_rng(seed).permutation(len(groups))
    n_needed = np.searchsorted(np.cumsum(counts[order]), extra_test) + 1
    test |= np.isin(group, groups[order[:n_needed]])
    return test


def make_models(args):
    return {
        "ridge": lambda: make_pipeline(StandardScaler(), Ridge(alpha=args.alpha)),
        "forest": lambda: RandomForestRegressor(n_estimators=args.trees, min_samples_leaf=3,
                                                max_features=0.5, n_jobs=-1, random_state=0),
    }


def print_table(title, values, specs, width=16):
    """values: {row name: [one number per specificity level]}"""
    print(title)
    print(f"{'':>{width}}" + "".join(f"{'spec=' + str(s):>11}" for s in specs))
    for name, row in values.items():
        print(f"{name:>{width}}" + "".join(f" {v:10.3f}" for v in row))


def main():
    text_models = [m for m, s in models.MODELS.items() if s["family"] != "dino"]
    p = argparse.ArgumentParser(description="Zero-shot recall from a fixed basket and the target's estimated size.")
    p.add_argument("--results_dir", type=str, required=True, help="Reference results folder (COCO: index.csv, labels.csv, dataset.json, <model>/)")
    p.add_argument("--model", type=str, required=True, choices=text_models, help="Open-vocabulary model providing the scores")
    p.add_argument("--sizes_file", type=str, default="object_sizes.json", help="Object size lookup table in results_dir")
    p.add_argument("--size_key", type=str, default="image_fraction", help="Which size value to use: image_fraction or surface_area_m2")
    p.add_argument("--basket_size", type=int, default=40, help="Number of categories in the reference basket; the rest are targets")
    p.add_argument("--basket_seeds", type=str, default="0,1,2,3,4", help="Comma-separated seeds, one random basket per seed")
    p.add_argument("--features", type=str, default="acc", help="Per-basket-category values in the query vector: any of acc,auc,rel")
    p.add_argument("--specs", type=str, default="0.8,0.9,0.95,0.99", help="Comma-separated specificity levels for the threshold")
    p.add_argument("--template", type=str, default="{}", help="Prompt template applied to each concept name")
    p.add_argument("--alpha", type=float, default=10.0, help="Ridge penalty on large weights; larger = more cautious")
    p.add_argument("--trees", type=int, default=200, help="Trees in the random forest")
    p.add_argument("--test_split", type=str, default="val2017", help="Split always placed in the test set")
    p.add_argument("--extra_test", type=int, default=20000, help="Additional images moved from other splits into the test set")
    p.add_argument("--split_seed", type=int, default=0, help="Seed for the test split")
    p.add_argument("--out_tag", type=str, default="", help="Optional tag appended to the output file names")
    p.add_argument("--plot", type=int, default=1, help="1 = write a predicted-vs-true recall plot (all baskets pooled)")
    args = p.parse_args()

    # ---- Load reference data, embeddings, and the size table ----
    with open(args.results_dir + "/dataset.json") as f:
        meta = json.load(f)
    assert meta["exhaustive"], "the reference set needs exhaustive labels"
    categories = meta["categories"]
    C = len(categories)
    with open(args.results_dir + "/index.csv") as f:
        index = list(csv.DictReader(f))
    model_dir = args.results_dir + "/" + args.model
    emb = models.load_embeddings(model_dir)
    assert emb.shape[0] == len(index), "embeddings incomplete: finish embed.py first"
    Y = label_matrix(args.results_dir, categories, len(index))
    test = make_test_mask(index, args.test_split, args.extra_test, args.split_seed)
    pool = ~test  # thresholds and query vectors come from the pool; test is only for true recall
    with open(args.results_dir + "/" + args.sizes_file) as f:
        size_table = json.load(f)
    missing = [c for c in categories if c not in size_table]
    assert not missing, f"no size for: {missing}"
    log_size = np.log([size_table[c][args.size_key] for c in categories])  # estimated size, log scale

    # ---- Zero-shot scores of every image for every concept ----
    model, processor = models.load(args.model, "cuda")
    texts = [args.template.format(c) for c in categories]
    text = models.encode_texts(args.model, model, processor, texts, "cuda").cpu().numpy()
    S = emb @ text.T  # (images x concepts)
    specs = [float(s) for s in args.specs.split(",")]

    # ---- Everything that does not depend on the basket, computed once ----
    # For query c and category k: auc[c, k] and mean score pos_mean[c, k].
    # For query c at specificity level j: threshold thr[c, j], acceptance acc[c, j, k],
    # true recall and true specificity on the test set.
    pos_pool = [np.where(pool & (Y[:, k] == 1))[0] for k in range(C)]
    auc = np.full((C, C), np.nan)
    pos_mean = np.zeros((C, C))
    thr = np.zeros((C, len(specs)))
    acc = np.zeros((C, len(specs), C))
    true_recall = np.zeros((C, len(specs)))
    true_spec = np.zeros((C, len(specs)))
    for c in range(C):
        s = S[:, c]
        for k in range(C):
            if k != c:
                auc[c, k] = roc_auc_score(Y[pool, k], s[pool])
            pos_mean[c, k] = s[pos_pool[k]].mean()
        neg_scores = s[pool & (Y[:, c] == 0)]
        for j, spec in enumerate(specs):
            thr[c, j] = np.quantile(neg_scores, spec)
            acc[c, j] = [(s[pos_pool[k]] > thr[c, j]).mean() for k in range(C)]
            true_recall[c, j] = (s[test & (Y[:, c] == 1)] > thr[c, j]).mean()
            true_spec[c, j] = (s[test & (Y[:, c] == 0)] <= thr[c, j]).mean()
        print(f"{c + 1}/{C} {categories[c]}", flush=True)

    # ---- Models that do not use the basket: leave one category out over all categories ----
    # P(Q|spec) and P(Q|spec, size), trained on the other 79 categories at each specificity level.
    no_basket = {"mean": np.zeros((C, len(specs)))}
    for name in make_models(args):
        no_basket["size_" + name] = np.zeros((C, len(specs)))
    for j in range(len(specs)):
        y_all = true_recall[:, j]
        for c in range(C):
            train = np.arange(C) != c
            no_basket["mean"][c, j] = y_all[train].mean()
            for name, make in make_models(args).items():
                fitted = make().fit(log_size[train][:, None], y_all[train])
                no_basket["size_" + name][c, j] = np.clip(fitted.predict(log_size[c:c + 1][:, None])[0], 0, 1)

    # ---- One experiment per random basket ----
    features = args.features.split(",")
    model_names = list(make_models(args))
    names = list(no_basket) + [f"acc_{m}" for m in model_names] + [f"acc+size_{m}" for m in model_names]
    all_err, all_bound, saved = [], [], []
    for seed in [int(x) for x in args.basket_seeds.split(",")]:
        perm = np.random.default_rng(seed).permutation(C)
        basket, targets = np.sort(perm[:args.basket_size]), np.sort(perm[args.basket_size:])
        err = {n: [] for n in names}
        bound = {n: [] for n in names}
        recall_row = []

        for j, spec in enumerate(specs):
            # Rows for this specificity level: one per target, inputs in fixed basket order.
            parts = {"acc": acc[targets][:, j][:, basket],
                     "auc": auc[targets][:, basket],
                     "rel": pos_mean[targets][:, basket] - thr[targets, j][:, None]}
            X_acc = np.hstack([parts[f] for f in features])
            X_acc_size = np.hstack([X_acc, log_size[targets][:, None]])  # add the target's own size
            y = true_recall[targets, j]
            recall_row.append(y.mean())

            preds = {n: np.zeros(len(targets)) for n in names}
            for n in no_basket:  # already computed above, against all other categories
                preds[n] = no_basket[n][targets, j]
            # Basket models: leave one target out, train on the other targets at this level.
            for i in range(len(targets)):
                train = np.arange(len(targets)) != i
                for name, make in make_models(args).items():
                    for label, X in (("acc", X_acc), ("acc+size", X_acc_size)):
                        fitted = make().fit(X[train], y[train])
                        preds[f"{label}_{name}"][i] = np.clip(fitted.predict(X[i:i + 1])[0], 0, 1)

            for n in names:
                e = np.abs(preds[n] - y)
                err[n].append(e.mean())
                bound[n].append(np.quantile(e, 0.9))
            for i, c in enumerate(targets):
                saved.append({"basket_seed": seed, "concept": categories[c], "spec": spec, "threshold": thr[c, j],
                              "est_size": float(np.exp(log_size[c])), "true_recall": y[i],
                              "true_spec": true_spec[c, j], **{"pred_" + n: preds[n][i] for n in names}})

        print(f"\n=== Basket seed {seed}: {len(basket)} basket categories, {len(targets)} targets ===")
        print("basket: " + ", ".join(categories[k] for k in basket))
        print_table("Average true recall:", {"true": recall_row}, specs)
        print_table("Typical |predicted - true recall|:", err, specs)
        print_table("90% of predictions within:", bound, specs)
        all_err.append(err)
        all_bound.append(bound)

    # ---- Average over baskets ----
    print(f"\n=== Average over {len(all_err)} baskets ===")
    print_table("Typical |predicted - true recall|:", {n: np.mean([e[n] for e in all_err], axis=0) for n in names}, specs)
    print_table("90% of predictions within:", {n: np.mean([b[n] for b in all_bound], axis=0) for n in names}, specs)

    # ---- Save ----
    tag = "_" + args.out_tag if args.out_tag else ""
    out = pd.DataFrame(saved)
    out_file = model_dir + "/basket_recall" + tag + ".csv"
    out.round(4).to_csv(out_file, index=False)
    print(f"\nWrote {out_file}")

    # ---- Optional plot: predicted vs true recall, all baskets pooled, colored by specificity ----
    if args.plot:
        fig, axes = plt.subplots(1, len(names), figsize=(3.5 * len(names), 3.5), sharex=True, sharey=True)
        for ax, name in zip(axes, names):
            sc = ax.scatter(out["pred_" + name], out.true_recall, c=out.spec, cmap="viridis", s=8)
            ax.plot([0, 1], [0, 1], color="red", linewidth=1)  # perfect prediction
            ax.set_title(name)
            ax.set_xlabel("predicted recall")
        axes[0].set_ylabel("true recall")
        fig.colorbar(sc, ax=axes, label="specificity level")
        plot_dir = model_dir + "/plots"
        os.makedirs(plot_dir, exist_ok=True)
        plot_file = plot_dir + "/basket_recall" + tag + ".png"
        fig.savefig(plot_file, dpi=150)
        plt.close(fig)
        print(f"Wrote {plot_file}")


if __name__ == "__main__":
    main()